#!/usr/bin/env python3
"""Run the external Honcho memory plugin's offline suite against THIS core checkout.

Owner-fork paired lane (.github/workflows/memory-author-guard.yml, job honcho-pair). The
plugin's own tests/pyproject.toml pins an old upstream hermes-agent, so it is not used:

  prepare  PM resolves the plugin's dependencies against this core as one explicit member
           (no config discovery, no eviction) under an isolated HOME/HERMES_HOME, and the
           SDK version is checked. Only the SDK package and its dist-info are then exposed to
           the dev+test interpreter, after its own copies of the SDK's requirements are
           checked to match the PM environment's.
  test     Each plugin test file runs in its own pytest process from a scrubbed environment,
           core first on sys.path, zero retries. Network-marked cases are deselected and
           counted; any other skipped case is not executed and fails. A generated control proves that an ID-less bot turn writes nothing
           through the real provider, the real session manager, and core's own loader and
           MemoryManager, against a fake SDK, while human and legacy turns still write.

Stdlib only; run it with the dev+test interpreter as ``python -I``.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

NETWORK_MARK = "allow_network"
FILE_TIMEOUT = 900
CONTROL_NAME = "test_pair_ci_idless_bot_control.py"
CORE_MODULES = ("agent", "hermes_cli", "tools", "run_agent")
NODE_ID = re.compile(r"^test_[^/:]*\.py::")

PM_PROGRAM = r"""
import importlib.metadata as md, json, subprocess, sys
from pathlib import Path
core, identity, source = (Path(a) for a in sys.argv[1:4])
sys.path.insert(0, str(core))
import pm
from pm.client import ensure_tools_for_sync
from pm.environments import selected_venv
from pm.plugin_inputs import Members
members = Members({identity: source})
ensure_tools_for_sync()
pm.sync_venv(["all"], explicit=True, plugins=members, evict_incompatible_plugins=False)
assert pm.venv_is_current(plugins=members), "PM environment is not current"
venv = selected_venv(core)
print("PM_SELECTED_VENV " + json.dumps(str(venv)), flush=True)
"""

PROBE_PROGRAM = r"""
import importlib.metadata as md, json, re, sys, sysconfig
dist = md.distribution("honcho-ai")
reqs = sorted({re.split(r"[\s;\[<>=!~(]", r, maxsplit=1)[0].lower()
               for r in (dist.requires or []) if "extra ==" not in r})
names = [n for n in sys.argv[1:] if n] or reqs
versions = {}
for name in names:
    try:
        versions[name] = md.version(name)
    except md.PackageNotFoundError:
        versions[name] = None
tops = {str(f).split("/")[0] for f in (dist.files or [])}
tops = sorted(t for t in tops if t not in ("..", "__pycache__"))
print(json.dumps({"python": sys.version.split()[0], "executable": sys.executable,
                  "soabi": sysconfig.get_config_var("SOABI"), "sdk": dist.version,
                  "site": str(dist.locate_file("")), "sdk_top": tops,
                  "requires": reqs, "versions": versions}))
"""

ORIGIN_PROGRAM = r"""
import importlib, importlib.metadata as md, json, sys
mods = sys.argv[1:]
out = {m: importlib.import_module(m).__file__ for m in mods}
out["honcho-ai"] = md.version("honcho-ai")
print(json.dumps(out))
"""

CONTROL_TEST = r'''"""Generated by scripts/ci/validate_honcho_pair.py; not part of the plugin.

An ID-less bot author must produce zero Honcho session/SDK writes; human and
legacy (no author) turns must still write. Real provider, real session
manager, a fake SDK from the client factory the manager reads, network blocked by
the plugin conftest.
"""
import importlib
import inspect
import os
from pathlib import Path
from unittest.mock import MagicMock

from hermes_plugin_honcho import HonchoMemoryProvider

IDLESS_BOT = {"id": None, "name": None, "is_bot": True}
HUMAN = {"id": "U123", "name": "Alice", "is_bot": False}
PLUGIN_DIR = Path(__file__).resolve().parent.parent


def _wire(provider, monkeypatch):
    package = type(provider).__module__  # the provider class lives in the package root
    client = importlib.import_module(package + ".client")
    session = importlib.import_module(package + ".session")
    sdk = MagicMock(name="honcho-sdk")
    monkeypatch.setattr(session, "get_honcho_client", lambda *_a, **_k: sdk)
    config = client.HonchoClientConfig(api_key="test-key", peer_name="eri",
                                       ai_peer="hermes", write_frequency="turn")
    provider._config = config
    provider._manager = session.HonchoSessionManager(honcho=sdk, config=config)
    provider._session_key = "slack:C1"
    provider._cron_skipped = False
    provider._session_initialized = True
    return sdk


def _join(provider):
    if provider._sync_thread:
        provider._sync_thread.join(timeout=10)
        assert not provider._sync_thread.is_alive()


def _writes(sdk):
    return [name for name, _args, _kw in sdk.mock_calls if name.endswith("add_messages")]


def test_idless_bot_turn_writes_nothing(monkeypatch):
    provider = HonchoMemoryProvider()
    sdk = _wire(provider, monkeypatch)
    provider.sync_turn("workflow post", "noted", turn_author=dict(IDLESS_BOT))
    _join(provider)
    assert provider._sync_thread is None
    assert sdk.mock_calls == []


def test_human_turn_still_writes(monkeypatch):
    provider = HonchoMemoryProvider()
    sdk = _wire(provider, monkeypatch)
    provider.sync_turn("hello", "hi", turn_author=dict(HUMAN))
    _join(provider)
    assert _writes(sdk)


def test_legacy_turn_without_author_still_writes(monkeypatch):
    provider = HonchoMemoryProvider()
    sdk = _wire(provider, monkeypatch)
    provider.sync_turn("hello", "hi")
    _join(provider)
    assert _writes(sdk)


def test_core_loader_and_memory_manager_route_idless_bot_to_no_writes(
        monkeypatch):
    plugins = Path(os.environ["HERMES_HOME"]) / "plugins"
    plugins.mkdir()
    (plugins / "honcho").symlink_to(PLUGIN_DIR, target_is_directory=True)
    from agent.memory_manager import MemoryManager
    from plugins.memory import load_memory_provider

    provider = load_memory_provider("honcho", register_skills=False)
    assert type(provider).__name__ == "HonchoMemoryProvider"
    assert Path(inspect.getfile(type(provider))).resolve().parent == PLUGIN_DIR
    assert "turn_source" in inspect.signature(provider.sync_turn).parameters
    manager = MemoryManager()
    manager.add_provider(provider)
    assert manager.accepts_turn_source()
    sdk = _wire(provider, monkeypatch)
    try:
        manager.sync_all("workflow post", "noted", session_id="s1",
                         turn_author=dict(IDLESS_BOT),
                         turn_source={"turn_id": "t1", "marker": "m1"})
        assert manager.flush_pending(timeout=10)
        _join(provider)
        assert sdk.mock_calls == []
        manager.sync_all("hello", "hi", session_id="s1", turn_author=dict(HUMAN))
        assert manager.flush_pending(timeout=10)
        _join(provider)
        assert _writes(sdk)
    finally:
        manager.shutdown_all()
'''


def _run(argv, *, env, cwd, timeout=FILE_TIMEOUT):
    return subprocess.run(argv, env=env, cwd=cwd, stdin=subprocess.DEVNULL,
                          capture_output=True, text=True, timeout=timeout, check=False)


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(["git", "-C", str(repo), *args], stdin=subprocess.DEVNULL,
                          capture_output=True, text=True, check=True, timeout=30).stdout.rstrip("\n")


def _scrubbed_env(state: Path, **extra: str) -> dict[str, str]:
    """A fresh environment: PATH and locale only, every home/cache/temp under ``state``."""
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LANG": "C.UTF-8",
           "TZ": "UTC", "PYTHONNOUSERSITE": "1", "PYTHONDONTWRITEBYTECODE": "1"}
    for key, child in (("HOME", "user"), ("HERMES_HOME", "home"),
                       ("HERMES_RUNTIME_DIR", "runtime"), ("TMPDIR", "tmp"),
                       ("XDG_CACHE_HOME", "cache"), ("XDG_CONFIG_HOME", "config")):
        path = state / child
        path.mkdir(mode=0o700, parents=True, exist_ok=True)
        env[key] = str(path)
    env.update(extra)
    return env


def _probe(python: str, env: dict[str, str], cwd: Path, names=()) -> dict:
    proc = _run([python, "-I", "-B", "-c", PROBE_PROGRAM, *names], env=env, cwd=cwd)
    if proc.returncode:
        raise SystemExit(f"probe failed under {python}:\n{proc.stdout}{proc.stderr}")
    return json.loads(proc.stdout)


def _pm_sync(core: Path, plugin: Path, state: Path, python: str) -> Path:
    env = _scrubbed_env(state / "pm")
    identity = Path(env["HERMES_HOME"]) / "plugins" / "honcho"
    argv = [python, "-I", "-B", "-c", PM_PROGRAM, str(core), str(identity), str(plugin)]
    proc = _run(argv, env=env, cwd=core, timeout=1800)
    (state / "pm-sync.log").write_text(proc.stdout + proc.stderr)
    marker = [ln for ln in proc.stdout.splitlines() if ln.startswith("PM_SELECTED_VENV ")]
    if proc.returncode or not marker:
        raise SystemExit(f"PM sync failed (exit {proc.returncode}):\n"
                         f"{proc.stdout[-4000:]}{proc.stderr[-4000:]}")
    venv = Path(json.loads(marker[-1].split(" ", 1)[1]))
    if not venv.resolve().is_relative_to(state.resolve()):
        raise SystemExit(f"PM selected an environment outside the state root: {venv}")
    return venv


def _bind_sdk(runtime: dict, state: Path) -> Path:
    """A directory holding only the SDK package(s) and dist-info, symlinked from PM's venv."""
    site = Path(runtime["site"])
    shim = state / "sdk-site"
    shim.mkdir(parents=True, exist_ok=False)
    if not any(t.endswith(".dist-info") for t in runtime["sdk_top"]):
        raise SystemExit(f"no dist-info among the SDK's files: {runtime['sdk_top']}")
    for name in runtime["sdk_top"]:
        if not (site / name).exists():
            raise SystemExit(f"SDK file root {name!r} missing from {site}")
        (shim / name).symlink_to(site / name)
    return shim


def _compare(runtime: dict, tester: dict, expect_sdk: str) -> list[str]:
    problems = []
    if runtime["sdk"] != expect_sdk:
        problems.append(f"PM resolved honcho-ai {runtime['sdk']}, expected {expect_sdk}")
    for key in ("python", "soabi"):
        if runtime[key] != tester[key]:
            problems.append(f"{key}: PM {runtime[key]} != test {tester[key]}")
    for name, version in runtime["versions"].items():
        if tester["versions"].get(name) != version:
            problems.append(f"SDK requirement {name}: PM {version} != test "
                            f"{tester['versions'].get(name)}")
    return problems


def _verify_origins(args, state: Path, pythonpath: str, venv: Path) -> dict:
    env = _scrubbed_env(state / "probe", PYTHONPATH=pythonpath)
    proc = _run([args.python, "-c", ORIGIN_PROGRAM, *CORE_MODULES, "honcho"],
                env=env, cwd=state)
    if proc.returncode:
        raise SystemExit(f"import origin probe failed:\n{proc.stdout}{proc.stderr}")
    origins = json.loads(proc.stdout)
    core = args.core.resolve()
    wrong = [m for m in CORE_MODULES if not Path(origins[m]).resolve().is_relative_to(core)]
    if wrong:
        raise SystemExit(f"core modules resolved outside {core}: {wrong} {origins}")
    if not Path(origins["honcho"]).resolve().is_relative_to(venv.resolve()):
        raise SystemExit(f"honcho resolved outside PM's environment: {origins['honcho']}")
    if origins["honcho-ai"] != args.expect_sdk:
        raise SystemExit(f"test interpreter sees honcho-ai {origins['honcho-ai']}")
    return origins


def cmd_prepare(args) -> int:
    state = args.state.resolve()
    if state.exists():
        raise SystemExit(f"state root must be fresh: {state}")
    state.mkdir(parents=True)
    venv = _pm_sync(args.core.resolve(), args.plugin.resolve(), state, args.python)
    env = _scrubbed_env(state / "probe")
    runtime = _probe(str(venv / "bin" / "python"), env, state)
    tester_env = _scrubbed_env(state / "probe", PYTHONPATH=str(args.core.resolve()))
    tester = _probe_tester(args.python, tester_env, state, runtime)
    problems = _compare(runtime, tester, args.expect_sdk)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    shim = _bind_sdk(runtime, state)
    pythonpath = os.pathsep.join([str(args.core.resolve()), str(shim)])
    origins = _verify_origins(args, state, pythonpath, venv)
    record = {"pm_selected_venv": str(venv), "pm_runtime": runtime, "test_python": tester,
              "sdk_site": str(shim), "pythonpath": pythonpath, "import_origins": origins}
    (state / "pair-env.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps(record, indent=2))
    return 0


def _probe_tester(python: str, env: dict, cwd: Path, runtime: dict) -> dict:
    """The test interpreter's own versions of the SDK's requirements (it lacks the SDK)."""
    code = ("import importlib.metadata as md, json, sys, sysconfig\n"
            "v = {}\nfor n in sys.argv[1:]:\n"
            "    try: v[n] = md.version(n)\n"
            "    except md.PackageNotFoundError: v[n] = None\n"
            "print(json.dumps({'python': sys.version.split()[0], 'executable': "
            "sys.executable, 'soabi': sysconfig.get_config_var('SOABI'), 'versions': v}))")
    proc = _run([python, "-c", code, *runtime["versions"]], env=env, cwd=cwd)
    if proc.returncode:
        raise SystemExit(f"test interpreter probe failed:\n{proc.stdout}{proc.stderr}")
    return json.loads(proc.stdout)


def _pytest(args, record: dict, tests: Path, extra: list[str], name: str):
    junit = args.state.resolve() / "junit" / f"{name}.xml"
    junit.parent.mkdir(parents=True, exist_ok=True)
    env = _scrubbed_env(args.state.resolve() / "pytest", PYTHONPATH=record["pythonpath"])
    argv = [args.python, "-m", "pytest", "-p", "no:cacheprovider", "-q",
            f"--junitxml={junit}", *extra]
    try:
        proc = _run(argv, env=env, cwd=tests)
    except subprocess.TimeoutExpired:
        return None, "", junit
    return proc.returncode, proc.stdout + proc.stderr, junit


def _collect(args, record: dict, tests: Path, marker: str | None) -> list[str]:
    extra = ["--collect-only", *(["-m", marker] if marker else [])]
    rc, out, _ = _pytest(args, record, tests, extra, f"collect-{marker or 'all'}")
    if rc != 0:
        raise SystemExit(f"collection failed (exit {rc}):\n{out[-6000:]}")
    return [ln for ln in out.splitlines() if NODE_ID.match(ln)]


def _junit_cases(junit: Path) -> list[tuple[str, str, str]]:
    if not junit.exists():
        return []
    cases = []
    for case in ET.parse(junit).getroot().iter("testcase"):
        kinds = {child.tag for child in case}
        outcome = next((k for k in ("error", "failure", "skipped") if k in kinds), "passed")
        cases.append((case.get("classname", ""), case.get("name", ""), outcome))
    return cases


def _run_file(args, record, tests, test_file, network_ids, all_ids) -> dict:
    marker = ["-m", f"not {NETWORK_MARK}"]
    rc, out, junit = _pytest(args, record, tests, [*marker, test_file], test_file)
    cases = _junit_cases(junit)
    in_file = [i for i in all_ids if i.split("::")[0] == test_file]
    expected = [i for i in in_file if i not in network_ids]
    all_network = bool(in_file) and not expected
    ok = (rc == 0 or (rc == 5 and all_network)) and len(cases) == len(expected)
    bad = [f"{c}::{n} {o}" for c, n, o in cases if o in ("error", "failure")]
    skipped = [f"{c}::{n}" for c, n, o in cases if o == "skipped"]
    result = {"file": test_file, "exit": rc, "ok": ok and not bad and not skipped,
              "cases": len(cases), "expected": len(expected),
              "network_deselected": len(in_file) - len(expected), "failed": bad,
              "skipped": skipped}
    if not result["ok"]:
        result["tail"] = out[-6000:]
    return result | {"_cases": cases}


def _verify_plugin(args, plugin: Path) -> dict:
    head, tree = _git(plugin, "rev-parse", "HEAD"), _git(plugin, "rev-parse", "HEAD^{tree}")
    dirty = _git(plugin, "status", "--porcelain", "--untracked-files=all")
    if (head, tree) != (args.expect_commit, args.expect_tree) or dirty:
        raise SystemExit(f"plugin checkout is not the exact clean commit: head={head} "
                         f"tree={tree} dirty={dirty!r}")
    count = len(_git(plugin, "ls-tree", "-r", "--name-only", "HEAD").splitlines())
    return {"head": head, "tree": tree, "files": count}


def _run_control(args, record, tests: Path) -> dict:
    control = tests / CONTROL_NAME
    control.write_text(CONTROL_TEST)
    try:
        rc, out, junit = _pytest(args, record, tests, [CONTROL_NAME], "control")
    finally:
        control.unlink()
    cases = _junit_cases(junit)
    passed = [n for _c, n, o in cases if o == "passed"]
    ok = rc == 0 and len(passed) == len(cases) == CONTROL_TEST.count("\ndef test_")
    return {"exit": rc, "ok": ok, "passed": passed, "cases": len(cases),
            **({} if ok else {"tail": out[-6000:]})}


def _core_identity(args) -> dict:
    core = args.core.resolve()
    head = _git(core, "rev-parse", "HEAD")
    if args.expect_core_sha and head != args.expect_core_sha:
        raise SystemExit(f"core HEAD {head} != expected {args.expect_core_sha}")
    dirty = _git(core, "status", "--porcelain").splitlines()
    return {"root": str(core), "head": head, "dirty_paths": [d[3:] for d in dirty]}


def _suite(args, record, tests: Path) -> dict:
    all_ids = _collect(args, record, tests, None)
    network_ids = set(_collect(args, record, tests, NETWORK_MARK))
    files = sorted({i.split("::")[0] for i in all_ids})
    results = [_run_file(args, record, tests, f, network_ids, all_ids) for f in files]
    # A skipped testcase was reported but not executed (and already failed its file).
    cases = [(r["file"], c, n) for r in results for c, n, o in r.pop("_cases")
             if o != "skipped"]
    return {"collected": len(all_ids), "unique_collected": len(set(all_ids)),
            "network_deselected": len(network_ids), "network_ids": sorted(network_ids),
            "files": len(files), "executed": len(cases), "unique_executed": len(set(cases)),
            "file_results": results}


def _tally(suite: dict) -> dict:
    failed = [f for r in suite["file_results"] for f in r["failed"]]
    bad_files = [r["file"] for r in suite["file_results"] if not r["ok"]]
    skipped = [s for r in suite["file_results"] for s in r["skipped"]]
    return {"failed_or_error": failed, "bad_files": bad_files, "skipped": skipped}


def cmd_test(args) -> int:
    record = json.loads((args.state.resolve() / "pair-env.json").read_text())
    plugin = args.plugin.resolve()
    tests = plugin / "tests"
    summary = {"core": _core_identity(args), "plugin": _verify_plugin(args, plugin),
               "sdk": record["pm_runtime"]["sdk"], "import_origins": record["import_origins"],
               "test_python": record["test_python"]["executable"], "file_retries": 0}
    suite = _suite(args, record, tests)
    suite.update(_tally(suite))
    summary["suite"] = suite
    summary["idless_bot_control"] = _run_control(args, record, tests)
    summary["plugin_after"] = _verify_plugin(args, plugin)
    problems = _problems(args, summary)
    summary["problems"] = problems
    _report(args, summary)
    return 1 if problems else 0


def _problems(args, summary: dict) -> list[str]:
    suite, problems = summary["suite"], []
    if suite["network_deselected"] != args.expect_network:
        problems.append(f"network-marked cases {suite['network_deselected']} "
                        f"!= expected {args.expect_network}")
    if suite["unique_executed"] != suite["executed"]:
        problems.append("duplicate testcase ids in JUnit results")
    if suite["skipped"]:
        problems.append(f"{len(suite['skipped'])} non-network testcase(s) skipped, not "
                        f"executed: {suite['skipped']}")
    if suite["executed"] != suite["collected"] - suite["network_deselected"]:
        problems.append(f"executed {suite['executed']} != collected "
                        f"{suite['collected']} - network {suite['network_deselected']}")
    problems += [f"file not green: {f}" for f in suite["bad_files"]]
    if not summary["idless_bot_control"]["ok"]:
        problems.append("ID-less bot control failed")
    return problems


def _report(args, summary: dict) -> None:
    suite = summary["suite"]
    (args.state.resolve() / "pair-summary.json").write_text(json.dumps(summary, indent=2))
    lines = [
        f"core HEAD {summary['core']['head']} (dirty: {len(summary['core']['dirty_paths'])})",
        f"plugin HEAD {summary['plugin']['head']} tree {summary['plugin']['tree']} "
        f"({summary['plugin']['files']} files), honcho-ai {summary['sdk']}",
        f"collected {suite['collected']} in {suite['files']} files; network deselected "
        f"{suite['network_deselected']}; executed {suite['executed']} "
        f"(unique {suite['unique_executed']}); failed/error {len(suite['failed_or_error'])}; "
        f"skipped {len(suite['skipped'])}",
        f"ID-less bot control: {'ok' if summary['idless_bot_control']['ok'] else 'FAILED'} "
        f"{summary['idless_bot_control']['passed']}",
    ]
    for result in suite["file_results"]:
        if not result["ok"]:
            lines.append(f"FAILED {result['file']} exit={result['exit']} {result['failed']}"
                         f" skipped={result['skipped']}")
            print(result.get("tail", ""))
    lines += [f"PROBLEM {p}" for p in summary["problems"]]
    print("\n".join(f"=== Paired Honcho: {ln}" for ln in lines))
    step_summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if step_summary:
        with open(step_summary, "a", encoding="utf-8") as fh:
            fh.write("### Paired Honcho plugin suite\n\n")
            fh.write("".join(f"- {ln}\n" for ln in lines))


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("prepare", "test"):
        p = sub.add_parser(name)
        p.add_argument("--core", type=Path, required=True)
        p.add_argument("--plugin", type=Path, required=True)
        p.add_argument("--state", type=Path, required=True)
        p.add_argument("--python", required=True, help="the dev+test interpreter")
        p.add_argument("--expect-sdk", required=True)
    test = sub.choices["test"]
    test.add_argument("--expect-commit", required=True)
    test.add_argument("--expect-tree", required=True)
    test.add_argument("--expect-network", type=int, required=True)
    test.add_argument("--expect-core-sha", default="")
    args = parser.parse_args(argv)
    return cmd_prepare(args) if args.command == "prepare" else cmd_test(args)


if __name__ == "__main__":
    raise SystemExit(main())
